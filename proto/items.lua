local function u16le(s, o)
  local a, b = s:byte(o, o + 1)
  return a + b * 256
end

local function u32le(s, o)
  local a, b, c, d = s:byte(o, o + 3)
  return a + b * 256 + c * 65536 + d * 16777216
end

-- Resolve a default location: <dir of this file>/../assets/items1530.bin, then cwd.
local function defaultPaths()
  local out = {}
  local src = debug.getinfo(1, 'S').source
  if src:sub(1, 1) == '@' then
    local dir = src:sub(2):match('^(.*)[/\\][^/\\]*$')
    if dir then
      out[#out + 1] = dir .. '/../assets/items1530.bin'
    end
  end
  out[#out + 1] = 'assets/items1530.bin'
  out[#out + 1] = 'items1530.bin'
  return out
end

-- ---------------------------------------------------------------------------
-- load
-- ---------------------------------------------------------------------------
-- path may be a file, or a directory containing items1530.bin, or nil (defaults).
function items.load(path)
  local candidates
  if path == nil then
    candidates = defaultPaths()
  elseif path:match('items1530%.bin$') then
    candidates = { path }
  else
    candidates = { path .. '/items1530.bin', path }
  end

  local f, used
  for _, p in ipairs(candidates) do
    local h = io.open(p, 'rb')
    if h then f, used = h, p break end
  end
  if not f then
    error('items.load: cannot open item table (tried: ' .. table.concat(candidates, ', ') .. ')', 2)
  end
  local blob = f:read('*a')
  f:close()
  if not blob then
    error('items.load: ' .. used .. ' could not be read', 2)
  end

  local function fail(fmt, ...)
    error('items.load: ' .. used .. ' ' .. string.format(fmt, ...), 3)
  end

  if #blob < items.HEADER_SIZE_V1 then fail('is truncated (header)') end
  if blob:sub(1, 4) ~= items.MAGIC then
    fail('bad magic %q (expected %q)', blob:sub(1, 4), items.MAGIC)
  end
  local version    = blob:byte(5)
  local headerSize = blob:byte(6)
  if version ~= 1 and version ~= 2 then
    fail('unsupported version %d (this loader reads 1 and 2)', version)
  end
  local wantHeader = (version == 1) and items.HEADER_SIZE_V1 or items.HEADER_SIZE
  if headerSize ~= wantHeader then
    fail('bad headerSize %d (expected %d for version %d)', headerSize, wantHeader, version)
  end
  if #blob < headerSize then fail('is truncated (header)') end

  local categoryCount = u16le(blob, 7)
  if categoryCount ~= 4 then
    fail('bad categoryCount %d (expected 4)', categoryCount)
  end

  local itemLen     = u32le(blob, 9)
  local creatureLen = u32le(blob, 13)
  local effectLen   = u32le(blob, 17)
  local missileLen  = u32le(blob, 21)
  local objectCount = u32le(blob, 25)
  local revision    = u16le(blob, 29)

  if itemLen < 2 or itemLen > 0x10000 then
    fail('implausible itemArrayLen %d', itemLen)
  end

  local sections = {}
  if version == 1 then
    -- v1: a single implicit FLAGS1 payload right after the 32-byte header.
    if #blob < 32 + itemLen then
      fail('truncated table (got %d bytes, want %d)', #blob - 32, itemLen)
    end
    if #blob > 32 + itemLen then
      fail('has trailing garbage after the table')
    end
    sections[items.S_FLAGS1] = { elem = 1, off = 32, len = itemLen }
  else
    local sectionCount = blob:byte(33)
    local dirOff       = u32le(blob, 37)
    if sectionCount < 1 or sectionCount > 64 then
      fail('implausible sectionCount %d', sectionCount)
    end
    if dirOff + sectionCount * items.DIR_ENTRY_SIZE > #blob then
      fail('section directory overruns the file')
    end
    for i = 0, sectionCount - 1 do
      local o   = dirOff + i * items.DIR_ENTRY_SIZE     -- 0-based
      local sid = blob:byte(o + 1)
      local elem = blob:byte(o + 2)
      local soff = u32le(blob, o + 5)
      local slen = u32le(blob, o + 9)
      if soff + slen > #blob then
        fail('section %d (offset %d, length %d) overruns the file', sid, soff, slen)
      end
      if sections[sid] then fail('duplicate section id %d in the directory', sid) end
      sections[sid] = { elem = elem, off = soff, len = slen }
    end
    -- FLAGS1 is the one section the protocol parser cannot live without.
    local s1 = sections[items.S_FLAGS1]
    if not s1 then fail('has no FLAGS1 section') end
    if s1.len ~= itemLen then
      fail('FLAGS1 length %d does not match itemArrayLen %d', s1.len, itemLen)
    end
  end

  -- Dense sections must be exactly elem*itemArrayLen so an in-range id can never
  -- read past the section; that check is what lets the accessors skip a length test.
  local DENSE = { [items.S_FLAGS1] = 1, [items.S_FLAGS2] = 1, [items.S_FLAGS3] = 1,
                  [items.S_FLAGS4] = 1, [items.S_FLAGS5] = 1, [items.S_MINIMAPCOLOR] = 1,
                  [items.S_ELEVATION] = 1, [items.S_CLOTHSLOT] = 1,
                  [items.S_GROUNDSPEED] = 2, [items.S_LENSHELP] = 2 }
  for sid, want in pairs(DENSE) do
    local s = sections[sid]
    if s then
      if s.elem ~= want then fail('section %d has elemSize %d (expected %d)', sid, s.elem, want) end
      if s.len ~= want * itemLen then
        fail('section %d has length %d (expected %d)', sid, s.len, want * itemLen)
      end
    end
  end
  if blob:byte(sections[items.S_FLAGS1].off + 1) ~= 0 then
    fail('FLAGS1 slot 0 must be 0x00, got 0x%02X', blob:byte(sections[items.S_FLAGS1].off + 1))
  end

  local nameIdx, nameBlob = sections[items.S_NAMEIDX], sections[items.S_NAMEBLOB]
  if nameIdx and not nameBlob then fail('has NAMEIDX but no NAMEBLOB') end
  if nameIdx then
    if nameIdx.elem ~= 6 then fail('NAMEIDX elemSize %d (expected 6)', nameIdx.elem) end
    if nameIdx.len % 6 ~= 0 then fail('NAMEIDX length %d is not a multiple of 6', nameIdx.len) end
  end

  BLOB = blob
  SEC  = sections
  items.sections = sections
  OFF1 = sections[items.S_FLAGS1].off
  OFF2 = sections[items.S_FLAGS2] and sections[items.S_FLAGS2].off
  OFF3 = sections[items.S_FLAGS3] and sections[items.S_FLAGS3].off
  OFF4 = sections[items.S_FLAGS4] and sections[items.S_FLAGS4].off
  OFF5 = sections[items.S_FLAGS5] and sections[items.S_FLAGS5].off
  if nameIdx then
    NAMEIDX_OFF, NAMEIDX_N, NAMEBLOB_OFF = nameIdx.off, nameIdx.len / 6, nameBlob.off
  else
    NAMEIDX_OFF, NAMEIDX_N, NAMEBLOB_OFF = 0, 0, 0
  end
  NAMECACHE = {}

  items.MAX_ID = itemLen - 1
  items.COUNT = objectCount
  items.CREATURE_MAX_ID = creatureLen - 1
  items.EFFECT_MAX_ID = effectLen - 1
  items.MISSILE_MAX_ID = missileLen - 1
  items.CONTENT_REVISION = revision
  items.fileVersion = version
  items.path = used
  items.loaded = true
  items.byteSize = #blob
  return items
end

function items.unload()
  BLOB, SEC, NAMECACHE = nil, nil, nil
  OFF1, OFF2, OFF3, OFF4, OFF5 = nil, nil, nil, nil, nil
  NAMEIDX_OFF, NAMEIDX_N, NAMEBLOB_OFF = 0, 0, 0
  items.sections = nil
  items.loaded = false
  items.path = nil
  items.fileVersion = 0
  items.byteSize = 0
  items.MAX_ID, items.COUNT = 0, 0
  items.CREATURE_MAX_ID, items.EFFECT_MAX_ID, items.MISSILE_MAX_ID = 0, 0, 0
  items.CONTENT_REVISION = 0
end

