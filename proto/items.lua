local function col1(sid, id, who)
  checkId(id, who)
  local s = SEC[sid]
  if not s then return 0 end
  return BLOB:byte(s.off + id + 1)
end

local function col2(sid, id, who)
  checkId(id, who)
  local s = SEC[sid]
  if not s then return 0 end
  return u16le(BLOB, s.off + id * 2 + 1)
end

-- bank.waypoints.  0 means "no bank block, or a bank with no waypoints"; see NOTE 3 --
-- the 100 / 150 substitutions belong to Tile::getGroundSpeed and Creature::getStepDuration,
-- NOT here.
function items.groundSpeed(id)  return col2(items.S_GROUNDSPEED,  id, 'groundSpeed')  end
function items.minimapColor(id) return col1(items.S_MINIMAPCOLOR, id, 'minimapColor') end
function items.elevation(id)    return col1(items.S_ELEVATION,    id, 'elevation')    end
function items.lensHelp(id)     return col2(items.S_LENSHELP,     id, 'lensHelp')     end
function items.clothSlot(id)    return col1(items.S_CLOTHSLOT,    id, 'clothSlot')    end

-- Appearance.name, or nil.  The index is sparse and sorted, so this binary-searches and
-- memoises; loading does NOT materialise 8 951 Lua strings up front.
function items.name(id)
  checkId(id, 'name')
  if NAMEIDX_N == 0 then return nil end
  local hit = NAMECACHE[id]
  if hit ~= nil then
    if hit == false then return nil end
    return hit
  end
  local lo, hi = 0, NAMEIDX_N - 1
  while lo <= hi do
    local mid = math.floor((lo + hi) / 2)
    local o = NAMEIDX_OFF + mid * 6
    local key = u16le(BLOB, o + 1)
    if key == id then
      local off = u32le(BLOB, o + 3)
      local s = NAMEBLOB_OFF + off + 1
      local e = BLOB:find('\0', s, true)
      local name = BLOB:sub(s, (e or (s + 1)) - 1)
      NAMECACHE[id] = name
      return name
    elseif key < id then
      lo = mid + 1
    else
      hi = mid - 1
    end
  end
  NAMECACHE[id] = false
  return nil
end

-- What `Item.create(id):getMarketData().name` returns in the real client: ThingType only
-- copies m_name into m_market.name inside `if (flags.has_market())` (thingtype.cpp:340-357),
-- so a named item with no market block hands the bot an empty string.  vBot works around
-- that with hardcoded ids (analyzer.lua:401 for 3031 "gold coin").  nil, not '', so the
-- caller can tell "no market name" from "market name is empty".
function items.marketName(id)
  if band(items.flags5(id), items.MARKET) == 0 then return nil end
  return items.name(id)
end

-- ---------------------------------------------------------------------------
-- ThingTypeManager::isValidDatId equivalents (size checks, not existence checks)
-- ---------------------------------------------------------------------------
function items.isValidItemId(id)
  return type(id) == 'number' and id >= 1 and id <= items.MAX_ID
end

function items.isValidCreatureId(id)
  return type(id) == 'number' and id >= 1 and id <= items.CREATURE_MAX_ID
end

function items.isValidEffectId(id)
  return type(id) == 'number' and id >= 1 and id <= items.EFFECT_MAX_ID
end

function items.isValidMissileId(id)
  return type(id) == 'number' and id >= 1 and id <= items.MISSILE_MAX_ID
end

-- convenience predicate over FLAGS1 (no extra allocation)
function items.has(id, mask)
  return band(items.flags(id), mask) ~= 0
end

