-- ThingType::hasElevation() -- the FLAG (has_height()), not `elevation(id) > 0`.
-- Tile::m_elevation counts things by this, and 4 ids carry height{elevation=0}.
function items.hasElevation(id)      return band(items.flags5(id), items.ELEVATION_BIT) ~= 0 end

-- Item::isStackable == ThingFlagAttrStackable == `cumulative` ALONE.  NOT FLAGS1's
-- CUMULATIVE bit, which the protocol reader also sets for liquidcontainer/liquidpool
-- (60 ids on this asset set).  targetbot/looting.lua:285 decides stack merging on this.
function items.isStackable(id)       return band(items.flags5(id), items.STACKABLE) ~= 0 end

-- Thing::isCommon (thing.h:67): not ground, not groundBorder, not onBottom, not onTop
-- (and not a creature -- creatures never reach this function).
function items.isCommon(id)
  return band(items.flags2(id), items.STACK_CLASS_MASK) == 0
end

-- Thing::getStackPriority (thing.cpp:54-77) for an ITEM.  Creatures are PRIO_CREATURE(4)
-- and are the caller's job; the `<= 800 && isSplash -> GROUND` clause is dead at 1530.
function items.stackPriority(id)
  local f = band(items.flags2(id), items.STACK_CLASS_MASK)
  if f == 0 then return items.PRIO_COMMON end
  if band(f, 0x01) ~= 0 then return items.PRIO_GROUND end
  if band(f, 0x02) ~= 0 then return items.PRIO_GROUND_BORDER end
  if band(f, 0x04) ~= 0 then return items.PRIO_ON_BOTTOM end
  return items.PRIO_ON_TOP
end

return items
