-- `who` is used only to build the error message, so the hot path never formats.
local function checkId(id, who)
  if BLOB == nil then
    error('items.' .. who .. ': item table not loaded (call items.load first)', 3)
  end
  if type(id) ~= 'number' or id ~= math.floor(id) then
    error('items.' .. who .. ': item id must be an integer, got ' .. tostring(id), 3)
  end
  if id < 1 or id > items.MAX_ID then
    error(string.format('items.%s: item id %d out of range 1..%d', who, id, items.MAX_ID), 3)
  end
end
items.checkId = checkId

-- Returns the FLAGS1 byte of an item id -- the v1 contract, unchanged.
-- 0 for holes and for ids in range with no flags; errors if id == 0 or id > MAX_ID.
function items.flags(id)
  checkId(id, 'flags')
  return BLOB:byte(OFF1 + id + 1)
end

function items.flags2(id)
  checkId(id, 'flags2')
  if not OFF2 then return 0 end
  return BLOB:byte(OFF2 + id + 1)
end

